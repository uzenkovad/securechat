"""Помилки бібліотеки. Усі збої шифрування перетворюються на CryptoError,
щоб Web API міг відповісти клієнту кодом 400, а не падати з внутрішньою помилкою."""


class CryptoError(Exception):
    """Не вдалося згенерувати ключ, зашифрувати або розшифрувати дані."""


class ProtocolError(Exception):
    """Повідомлення протоколу безпечного каналу має неправильну структуру."""
